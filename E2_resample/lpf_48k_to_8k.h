int downsample_48k_to_8k(const float *x, int n_in, float *y)
{
    int count = 0;
    int i, k;
    for (i = 0; i < n_in; i += LPF_Q) {
        float acc = 0.0f;
        for (k = 0; k < LPF_LEN; k++) {
            int idx = i - k;
            if (idx >= 0) acc += lpf_coeff[k] * x[idx];
        }
        y[count++] = acc;
    }
    return count;
}

