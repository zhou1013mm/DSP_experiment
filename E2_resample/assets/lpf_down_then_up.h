/* 48k -> 8k 抗混叠降采样 */
static inline int downsample_48k_to_8k(const float *x, int n_in, float *y)
{
    int count = 0;
    int i, k;
    for (i = 0; i < n_in; i += DEC_FIR_Q) {
        float acc = 0.0f;
        for (k = 0; k < DEC_FIR_LEN; k++) {
            int idx = i - k;
            if (idx >= 0) acc += dec_fir_coeff[k] * x[idx];
        }
        y[count++] = acc;
    }
    return count;
}

/* 8k 域 IIR 低通 (DF2T, 状态跨调用保持) */
static inline void iir_lpf_8k(const float *x, float *y, int n)
{
    static float z[LPF_IIR_N_SOS][2] = {{0.0f}};
    int i, s;
    for (i = 0; i < n; i++) {
        float in = x[i];
        for (s = 0; s < LPF_IIR_N_SOS; s++) {
            const float *c = lpf_iir_sos[s];
            float out = c[0] * in + z[s][0];
            z[s][0] = c[1] * in - c[4] * out + z[s][1];
            z[s][1] = c[2] * in - c[5] * out;
            in = out;
        }
        y[i] = in * LPF_IIR_GAIN;
    }
}

/* 8k -> 48k 多相上采样 */
static inline int upsample_8k_to_48k(const float *x, int n_in, float *y)
{
    const int P = INT_FIR_P;
    const int branch_len = (INT_FIR_LEN + P - 1) / P;
    int n, m;
    for (n = 0; n < n_in * P; n++) {
        int phase = n % P;
        int q     = n / P;
        float acc = 0.0f;
        for (m = 0; m < branch_len; m++) {
            int hidx = phase + m * P;
            if (hidx >= INT_FIR_LEN) break;
            int xidx = q - m;
            if (xidx >= 0 && xidx < n_in)
                acc += int_fir_coeff[hidx] * x[xidx];
        }
        y[n] = acc;
    }
    return n_in * P;
}

